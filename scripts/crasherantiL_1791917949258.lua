    -- ============================================================
    -- ÉTAT
    -- ============================================================
    local State = {
        Active = false,
        LoopThread = nil,
        OriginalParent = nil,
        Character = nil,
        Humanoid = nil,
        Valid = nil,
        PhysicsLoop = nil,
        InitConn = nil,
        Keybind = Enum.KeyCode.R,
    }
    
    -- ============================================================
    -- FONCTIONS DU SCRIPT ORIGINAL
    -- ============================================================
    
    -- Boucle de physics (physics rep root part)
    local function startPhysicsLoop(character, humanoid, valid)
        return task.spawn(function()
            while State.Active and character and character.Parent do
                for index, current in valid do
                    pcall(function()
                        sethiddenproperty(current, "PhysicsRepRootPart", valid[index + 1] or valid[1])
                    end)
                end
                task.wait()
            end
        end)
    end
    
    -- Reset immédiat (les 5 itérations)
    local function immediateReset(humanoid)
        if not humanoid then return end
        for _ = 1, 5 do
            pcall(function()
                replicatesignal(humanoid.ServerBreakJoints)
                replicatesignal(humanoid.ServerResetCharacter)
            end)
        end
    end
    
    -- Boucle principale de reset
    local function mainResetLoop(character, humanoid)
        return task.spawn(function()
            for _ = 1, 9e9 do
                if not State.Active then break end
                if not character or not character.Parent then break end
                if not humanoid or not humanoid.Parent then break end
                
                pcall(function()
                    replicatesignal(humanoid.ServerBreakJoints)
                    replicatesignal(humanoid.ServerResetCharacter)
                    character.Parent = LightingService
                end)
                task.wait()
            end
        end)
    end
    
    -- ============================================================
    -- ACTIVATION / DÉSACTIVATION
    -- ============================================================
    
    local function activateReset()
        if State.Active then return end
        
        local character = LocalPlayer.Character
        if not character then
            warn("[Reset] Aucun personnage trouvé.")
            return false
        end
        
        local humanoid = character:FindFirstChildWhichIsA("Humanoid")
        if not humanoid then
            warn("[Reset] Aucun Humanoid trouvé.")
            return false
        end
        
        local valid = character:QueryDescendants("BasePart") or {}
        if #valid == 0 then
            warn("[Reset] Aucun BasePart trouvé.")
            return false
        end
        
        State.Active = true
        State.Character = character
        State.Humanoid = humanoid
        State.Valid = valid
        State.OriginalParent = character.Parent
        
        -- Lancer la boucle physics
        State.PhysicsLoop = startPhysicsLoop(character, humanoid, valid)
        
        -- Attendre 0.1s puis reset immédiat
        task.wait(0.1)
        
        if not State.Active then return false end
        immediateReset(humanoid)
        
        task.wait(0.1)
        
        -- Lancer la boucle principale
        if State.Active then
            State.LoopThread = mainResetLoop(character, humanoid)
        end
        
        print("[Reset] ACTIVÉ")
        return true
    end
    
    local function deactivateReset()
        if not State.Active then return end
        State.Active = false
        
        -- Restaurer le parent du personnage
        if State.Character and State.Character.Parent == LightingService then
            pcall(function()
                State.Character.Parent = State.OriginalParent or workspace
            end)
        end
        
        -- Nettoyer
        State.LoopThread = nil
        State.PhysicsLoop = nil
        State.Character = nil
        State.Humanoid = nil
        State.Valid = nil
        
        print("[Reset] DÉSACTIVÉ")
    end
    
