    			local warned = false
    			while running do
    				if not remote or not remote.Parent then remote = findRemote() end
    				if remote then
    					pcall(function() remote:FireServer(payload) end)
    					task.wait(FIXED_DELAY)
    					warned = false
    				else
    					if not warned then
    						print("[DXVINE] SetPlayerBlockList NOT FOUND")
    						warned = true
    					end
    					task.wait(0.5)
    				end
    			end
    		end)
    	else
    		if loopTask then pcall(task.cancel, loopTask) end
    		loopTask = nil
    		payload = nil
    		print("[DXVINE] STOP")
    	end
    end
    
