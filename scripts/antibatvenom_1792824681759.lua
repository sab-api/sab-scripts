    		if not root or not root.Parent then
    			return
    		end
    
    		local savedXZ = Vector3.new(root.Velocity.X, 0, root.Velocity.Z)
    
    		spikeAmplitude = spikeAmplitude + 500 * spikeDirection
    
    		if spikeAmplitude >= 20000 then
    			spikeAmplitude = 10000
    			spikeDirection = -1
    		elseif spikeAmplitude <= 10000 then
    			spikeAmplitude = 10000
    			spikeDirection = 1
    		end
    
    		spikePhase = spikePhase + math.random() * 0.5
    		local magnitude = spikeAmplitude + math.random(-5000, 5000)
    		local spikeX = math.cos(spikePhase) * magnitude
    		local spikeZ = math.sin(spikePhase) * magnitude
    
    		_G._VenomAntiBatSpiking = true
    		root.Velocity = Vector3.new(spikeX, root.Velocity.Y, spikeZ)
    
    		RunService.RenderStepped:Wait()
    
    		if root.Parent then
    			local desired = _G._VenomAntiBatDesiredXZ
    			if desired then
    				root.Velocity = Vector3.new(desired.X, root.Velocity.Y, desired.Z)
    			else
    				root.Velocity = Vector3.new(savedXZ.X, root.Velocity.Y, savedXZ.Z)
    			end
    		end
    
    		_G._VenomAntiBatSpiking = false
    	end)
    end
    
