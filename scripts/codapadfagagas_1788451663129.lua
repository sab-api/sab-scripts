    local function isValidCode(msg)
        return type(msg) == "string" and #msg >= 2 and msg:match("^[A-Za-z0-9]+$") ~= nil
    end
    
    local function updatePreview()
        if #buffer == 0 then previewBox.Text = ""; return end
        previewBox.Text = table.concat(buffer, "", 1, math.min(#buffer, mode))
    end
    
    local function processBuffer()
        if not scanning then return end
        while scanning and #buffer >= mode do
            local combined = table.concat(buffer, "", 1, mode)
            buffer = {}; updatePreview()
            task.spawn(typeAndSubmitCode, combined)
            task.wait(delay)
        end
        updatePreview()
    end
    
    -- ══════════════════════════════════════
    -- ANNOUNCEMENT CAPTURE
    -- catches both plain string args AND
    -- table/dict-style notification payloads
    -- ══════════════════════════════════════
    local function extractText(...)
        local args = {...}
        for _, v in ipairs(args) do
            if type(v) == "string" and v ~= "" then
                local clean = v:match("^%s*(.-)%s*$")
                if isValidCode(clean) then return clean end
            elseif type(v) == "table" then
                for _, tv in pairs(v) do
                    if type(tv) == "string" and tv ~= "" then
                        local clean = tv:match("^%s*(.-)%s*$")
                        if isValidCode(clean) then return clean end
                    end
                end
            end
        end
        return nil
    end
    
    local function onAnnouncement(...)
        if not scanning then return end
        local code = extractText(...)
        if code then
            table.insert(buffer, code)
            updatePreview()
            print("[nexus flow] captured:", code, "buffer:", #buffer)
            if #buffer >= mode then task.spawn(processBuffer) end
        end
    end
    
